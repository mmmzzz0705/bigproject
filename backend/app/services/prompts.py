def build_context(hits) -> str:
    """把召回片段拼装成参考资料。

    带 `meta["aux"]` 的片段是"材料表补齐"用的辅助片段（多为填报须知/表格附注），
    只服务于抽取式兜底，不进生成上下文 —— 否则会稀释有效信息，
    模型可能据此判定"资料里没讲清楚"而拒答。
    """
    parts = []
    n = 0
    for h in hits:
        if h.meta.get("aux"):
            continue
        n += 1
        head = f"[{n}] 《{h.doc_name}》" + (f" · {h.section}" if h.section else "")
        parts.append(f"{head}\n{h.text}")
    return "\n\n".join(parts)


def build_history(history: list[tuple[str, str]]) -> str:
    """把历史对话拼装成文本。"""
    if not history:
        return "（无）"
    return "\n".join(f"用户：{q}\n助手：{a}" for q, a in history)
