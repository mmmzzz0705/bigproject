/** 关键词匹配打分，返回命中的知识条目 */
export function mockAnswer(question) {
  const q = (question || '').trim()
  let best = null
  let bestScore = 0
  for (const item of KB) {
    const score = item.keywords.reduce((acc, k) => (q.includes(k) ? acc + k.length : acc), 0)
    if (score > bestScore) {
      bestScore = score
      best = item
    }
  }
  if (!best) {
    return { answer: NO_HIT_ANSWER, material_list: null, sources: [] }
  }
  return {
    answer: best.answer,
    material_list: best.material,
    sources: best.sources
  }
}

